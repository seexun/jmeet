/** Fallback icon for unknown/unmapped material names. */
export const DEFAULT_NZ_ICON_TYPE = 'file-text';

/**
 * Resolve a legacy Material icon name to an nz-icon `nzType`.
 * Unknown names fall back to `DEFAULT_NZ_ICON_TYPE` so the UI never renders
 * a broken (dynamically fetched) icon.
 */
export function nzIconType(materialName: string | null | undefined, fallback: string = DEFAULT_NZ_ICON_TYPE): string {
	if (!materialName) {
		return fallback;
	}
	return MATERIAL_ICON_MAP[materialName] ?? fallback;
}

